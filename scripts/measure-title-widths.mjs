// Measures how wide every character is in each design's page title, and
// prints src/designs/titleWidths.ts. titleFit uses those widths to shrink a
// title only as far as its widest word needs to fit, so run this again when a
// design changes its title's typeface, weight, variation settings or letter
// spacing:
//
//   npm run build && PORT=3999 npm start &
//   CHROME=/path/to/chrome node scripts/measure-title-widths.mjs http://127.0.0.1:3999 > src/designs/titleWidths.ts
//
// It drives a headless Chrome over the DevTools protocol, so it needs nothing
// installed beyond Chrome itself.
import { spawn } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const base = process.argv[2] ?? "http://127.0.0.1:3000";
const chrome = process.env.CHROME;
if (!chrome) throw new Error("set CHROME to a Chrome or Chromium binary");

export const chars = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ..."‘’“”–—…"].join("");
const designs = ["safe", "bold", "experimental"];

// Draws each character twenty times in the title's own style, at a size of its
// own (letter spacing in em, so it scales), and returns its width in ems.
const measure = (all) => `(() => {
  const h = document.querySelector("h1.doc-title");
  const style = getComputedStyle(h);
  const spacing = parseFloat(style.letterSpacing) / parseFloat(style.fontSize) || 0;
  return [...${JSON.stringify(all)}].map((c) => {
    const s = document.createElement("span");
    s.style.cssText = "display:inline-block;white-space:pre;font-size:100px;letter-spacing:" + spacing + "em";
    s.textContent = c.repeat(20);
    h.appendChild(s);
    const width = s.getBoundingClientRect().width / 20 / 100;
    s.remove();
    return Math.round(width * 1000);
  });
})()`;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const profile = mkdtempSync(join(tmpdir(), "title-widths-"));
const port = 9222 + Math.floor(Math.random() * 500);
const browser = spawn(chrome, ["--headless=new", "--no-sandbox", "--disable-gpu", `--remote-debugging-port=${port}`, `--user-data-dir=${profile}`, "about:blank"], { stdio: "ignore" });

try {
  let target;
  for (let i = 0; i < 100 && !target; i++) {
    try {
      target = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find((t) => t.type === "page");
    } catch {
      await sleep(100);
    }
  }
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((r) => ws.addEventListener("open", r, { once: true }));
  let id = 0;
  const waiting = new Map();
  const events = [];
  ws.addEventListener("message", (m) => {
    const d = JSON.parse(m.data);
    if (d.id && waiting.has(d.id)) waiting.get(d.id)(d);
    else events.push(d.method);
  });
  const send = (method, params = {}) => new Promise((r) => { waiting.set(++id, r); ws.send(JSON.stringify({ id, method, params })); });
  await send("Page.enable");

  const tables = {};
  for (const design of designs) {
    events.length = 0;
    await send("Page.navigate", { url: `${base}/docs?design=${design}` });
    for (let i = 0; i < 100 && !events.includes("Page.loadEventFired"); i++) await sleep(100);
    await send("Runtime.evaluate", { expression: "document.fonts.ready", awaitPromise: true });
    const result = await send("Runtime.evaluate", { expression: measure(chars), returnByValue: true });
    tables[design] = result.result.result.value;
  }
  ws.close();

  const lines = (numbers) => numbers.join(" ").match(/.{1,96}(\s|$)/g).map((l) => `  "${l.trim()} " +`).join("\n").replace(/ " \+$/, '"');
  console.log(`// Generated by scripts/measure-title-widths.mjs: do not edit by hand, run it again.
// How wide each character is in each design's page title, in thousandths of an
// em, letter spacing included, measured in Chrome. titleFit adds them up to find
// how wide a title's widest word is.

export const titleChars = ${JSON.stringify(chars)};

export type TitleWidths = readonly number[];

const parse = (widths: string): TitleWidths => widths.trim().split(" ").map(Number);
${designs
  .map((d) => `\nexport const ${d}TitleWidths = parse(\n${lines(tables[d])},\n);`)
  .join("\n")}`);
} finally {
  browser.kill();
  for (let i = 0; i < 20; i++) {
    try {
      rmSync(profile, { recursive: true });
      break;
    } catch {
      await sleep(250);
    }
  }
}
